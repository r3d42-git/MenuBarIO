function translate(value) {
  if (typeof value === 'string') return translations.get(value) ?? value;
  if (Array.isArray(value)) return value.map(translate);
  if (value && typeof value === 'object') {
    return Object.fromEntries(Object.entries(value).map(([key, item]) => [key, translate(item)]));
  }
  return value;
}

await mkdir(destinationDirectory, { recursive: true });
const sourceFiles = (await readdir(sourceDirectory))
  .filter((name) => name.endsWith('.json'))
  .sort();

for (const filename of sourceFiles) {
  const source = JSON.parse(await readFile(resolve(sourceDirectory, filename), 'utf8'));
  const english = translate(source);
  english.meta = { ...english.meta, locale: 'en' };
  await writeFile(resolve(destinationDirectory, filename), `${JSON.stringify(english, null, 2)}\n`);
}

console.log(`Wrote ${sourceFiles.length} English Archify specifications.`);
